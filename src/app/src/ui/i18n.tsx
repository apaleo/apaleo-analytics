export type MessageKey = keyof typeof en

/** Dates and numbers use English. There is no locale preference. */
export const UI_LOCALE = 'en' as const

/** English copy only. Locale is not part of the UI. */
export const messages = { en } as const

export function t(key: MessageKey): string {
  return en[key]
}

const I18nContext = createContext<{ t: (key: MessageKey) => string } | null>(null)

export function useI18n(): { t: (key: MessageKey) => string } {
  const value = useContext(I18nContext)
  if (value === null) throw new Error('useI18n must be used within I18nProvider')
  return value
}

export function I18nProvider({ children }: { children: ReactNode }) {
  useEffect(() => {
    document.documentElement.lang = 'en'
  }, [])

  const value = useMemo(() => ({ t }), [])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}
